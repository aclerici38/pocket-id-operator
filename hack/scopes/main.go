// Command scopes prints the API key scopes each resource needs as a Markdown page, from the
// Pocket ID client methods its controller package can reach.
package main

import (
	"fmt"
	"go/ast"
	"go/types"
	"log"
	"maps"
	"slices"
	"strings"

	"github.com/aclerici38/pocket-id-go-client/v3/client"
	"golang.org/x/tools/go/packages"
)

const (
	module     = "github.com/aclerici38/pocket-id-operator"
	clientPath = "github.com/aclerici38/pocket-id-go-client/v3/client"
)

func main() {
	pkgs, err := packages.Load(&packages.Config{
		Mode: packages.NeedName | packages.NeedTypes | packages.NeedSyntax | packages.NeedTypesInfo,
	}, "./api/...", "./internal/...")
	if err != nil {
		log.Fatal(err)
	}

	kinds := map[string]string{} // lowercase Kind -> Kind
	calls := map[*types.Func][]string{}
	refs := map[*types.Func][]*types.Func{}
	roots := map[string][]*types.Func{} // Kind -> functions of its controller package
	for _, pkg := range pkgs {
		if len(pkg.Errors) > 0 {
			log.Fatalf("load %s: %v", pkg.PkgPath, pkg.Errors)
		}
		if pkg.PkgPath == module+"/api/v1alpha1" {
			for _, name := range pkg.Types.Scope().Names() {
				kinds[strings.ToLower(name)] = name
			}
		}
	}
	for _, pkg := range pkgs {
		kind := kinds["pocketid"+pkg.Name]
		for _, file := range pkg.Syntax {
			if strings.HasSuffix(pkg.Fset.File(file.Pos()).Name(), "_test.go") {
				continue
			}
			for _, decl := range file.Decls {
				fd, ok := decl.(*ast.FuncDecl)
				if !ok {
					continue
				}
				fn := pkg.TypesInfo.Defs[fd.Name].(*types.Func)
				if kind != "" {
					roots[kind] = append(roots[kind], fn)
				}
				ast.Inspect(fd, func(n ast.Node) bool {
					switch n := n.(type) {
					case *ast.SelectorExpr:
						// The admin client embeds *client.Client, so its calls are promoted methods; a
						// direct call on *client.Client is a user session's, not the API key's.
						sel := pkg.TypesInfo.Selections[n]
						if sel != nil && sel.Kind() == types.MethodVal && len(sel.Index()) > 1 && pkgPath(sel.Obj()) == clientPath {
							calls[fn] = append(calls[fn], sel.Obj().Name())
						}
					case *ast.Ident:
						if f, ok := pkg.TypesInfo.Uses[n].(*types.Func); ok && strings.HasPrefix(pkgPath(f), module+"/") {
							refs[fn] = append(refs[fn], f.Origin())
						}
					}
					return true
				})
			}
		}
	}

	fmt.Println("<!-- Generated by `mise run generate-api-docs` from hack/scopes; do not edit by hand. -->")
	fmt.Print(`
# API Key Scopes

The scopes an API key needs for the operator to manage each resource on an
[external instance](../guides/pocketidinstance.md#api-key-scopes).

| Resource | Scopes |
| --- | --- |
`)
	var all []string
	for _, kind := range slices.Sorted(maps.Keys(roots)) {
		seen := map[*types.Func]bool{}
		var ops []string
		var walk func(*types.Func)
		walk = func(fn *types.Func) {
			if seen[fn] {
				return
			}
			seen[fn] = true
			ops = append(ops, calls[fn]...)
			for _, r := range refs[fn] {
				walk(r)
			}
		}
		for _, fn := range roots[kind] {
			walk(fn)
		}
		scopes, err := client.Scopes(client.SchemeAPIKey, ops...)
		if err != nil {
			log.Fatalf("%s: %v", kind, err)
		}
		all = append(all, scopes...)
		fmt.Printf("| [%s](%s.md) | %s |\n", kind, strings.ToLower(kind), code(scopes))
	}
	slices.Sort(all)
	fmt.Printf("| All | %s |\n", code(slices.Compact(all)))
}

// pkgPath returns the path of obj's package, or "" for a universe object such as error.Error.
func pkgPath(obj types.Object) string {
	if obj.Pkg() == nil {
		return ""
	}
	return obj.Pkg().Path()
}

func code(scopes []string) string {
	return "`" + strings.Join(scopes, "`, `") + "`"
}
