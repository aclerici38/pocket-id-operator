// CustomClaimsEqual compares two CustomClaim slices for equality regardless of order.
func CustomClaimsEqual(a, b []CustomClaim) bool {
	if len(a) == 0 && len(b) == 0 {
		return true
	}
	if len(a) != len(b) {
		return false
	}
	aMap := make(map[string]string, len(a))
	for _, c := range a {
		aMap[c.Key] = c.Value
	}
	for _, c := range b {
		if v, ok := aMap[c.Key]; !ok || v != c.Value {
			return false
		}
	}
	return true
}

func orderedEqual(a, b []string) bool {
	if len(a) == 0 && len(b) == 0 {
		return true
	}
	if len(a) != len(b) {
		return false
	}
	for i := range a {
		if a[i] != b[i] {
			return false
		}
	}
	return true
}

// SortedEqual compares two string slices for equality regardless of order.
func SortedEqual(a, b []string) bool {
	if len(a) == 0 && len(b) == 0 {
		return true
	}
	if len(a) != len(b) {
		return false
	}
	aCopy := make([]string, len(a))
	bCopy := make([]string, len(b))
	copy(aCopy, a)
	copy(bCopy, b)
	sort.Strings(aCopy)
	sort.Strings(bCopy)
	for i := range aCopy {
		if aCopy[i] != bCopy[i] {
			return false
		}
	}
	return true
}

// NewClient creates a new Pocket-ID client for the given base URL with optional API key.
func NewClient(baseURL string, apiKey string, opts ...ClientOption) (*Client, error) {
	parsed, err := url.Parse(baseURL)
	if err != nil {
		return nil, fmt.Errorf("parse base URL: %w", err)
	}

	c := &Client{baseURL: parsed.Scheme + "://" + parsed.Host}
	for _, opt := range opts {
		opt(c)
	}

	transport := httptransport.NewWithClient(parsed.Host, "/", []string{parsed.Scheme}, c.httpClient)

	if apiKey != "" {
		transport.DefaultAuthentication = runtime.ClientAuthInfoWriterFunc(
			func(req runtime.ClientRequest, reg strfmt.Registry) error {
				return req.SetHeaderParam("X-API-KEY", apiKey)
			},
		)
	}

	// Every operation declares a default error response, so go-swagger deserializes
	// error bodies instead of just recording the status code.
	for _, mime := range []string{runtime.TextMime, runtime.HTMLMime, runtime.DefaultMime} {
		transport.Consumers[mime] = discardingConsumer{}
	}

	c.raw = apiclient.New(transport, strfmt.Default)

	return c, nil
}

// discardingConsumer drains a response body without decoding it, so the surrounding
// response type (and its status code) survives a body it cannot parse.
type discardingConsumer struct{}

func (discardingConsumer) Consume(reader io.Reader, _ any) error {
	_, err := io.Copy(io.Discard, reader)
	return err
}

